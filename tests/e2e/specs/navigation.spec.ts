import { expect, test, APIRequestContext, Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { resolve } from 'node:path';

async function post(api: APIRequestContext, path: string, data: unknown) {
  const token = await (await api.get('/api/auth/csrf')).json();
  const response = await api.post(`/api${path}`, { data, headers: { [token.headerName]: token.token } });
  expect(response.ok(), await response.text()).toBeTruthy();
  return response.json();
}

async function accessible(page: Page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map(({ target }) => target) }))).toEqual([]);
}

